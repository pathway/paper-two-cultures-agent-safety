"""Locate quoted phrases in the stored full texts, so that a reader can check each one cheaply. Pure functions.

Chain of evidence: 200_draft / tables -> 047_extracts/<key>/extracts.csv -> 045_fulltext/<key>.txt (file and line).
Matching ignores whitespace, typographic quotes, ligatures and hyphens at line ends, because PDF text extraction
breaks lines and words freely. A phrase with an ellipsis (…) matches when its parts occur in order.
"""
from collections import namedtuple

import re

ELLIPSIS = "…"
QUOTED = re.compile(r'"([^"]+)"')
FOLD = {"“": '"', "”": '"', "‘": "'", "’": "'", "ﬁ": "fi", "ﬂ": "fl", "ﬀ": "ff", "ﬃ": "ffi", "ﬄ": "ffl"}

Index = namedtuple("Index", "chars lines")      # non-space characters of a text, and the line number of each
Hit = namedtuple("Hit", "line context")         # first line of a match, and that line's text
Use = namedtuple("Use", "key where phrase")     # a quoted phrase, the source it is attributed to, and where it is used


def compact(text):
    """Text with typography folded and all whitespace removed."""
    return "".join(FOLD.get(c, c) for c in text if not c.isspace())


def build_index(text):
    """Index of a full text. A hyphen that ends a line is dropped, so words split by the PDF are whole again."""
    chars, lines = [], []
    for number, line in enumerate(text.split("\n"), 1):
        body = line.rstrip()
        if body.endswith("-"):
            body = body[:-1]
        for c in body:
            if not c.isspace():
                folded = FOLD.get(c, c)
                chars.append(folded)
                lines.extend([number] * len(folded))
    return Index("".join(chars), lines)


def locate(index, phrase):
    """Line number where `phrase` starts in the indexed text, or None. Parts around an ellipsis must occur in order."""
    start, first = 0, None
    for part in (compact(p) for p in phrase.split(ELLIPSIS)):
        if not part:
            continue
        candidates = [part, part.replace("-", "")]          # the phrase may keep a hyphen that the index dropped
        found = min((i for i in (index.chars.find(c, start) for c in candidates) if i >= 0), default=-1)
        if found < 0:
            return None
        first = index.lines[found] if first is None else first
        start = found + 1
    return first


def page_of(fulltext, line):
    """Page of the PDF that holds this line of its extracted text (pages are separated by form feeds), or None."""
    if "\f" not in fulltext:
        return None
    return fulltext[:sum(len(x) + 1 for x in fulltext.split("\n")[:line - 1])].count("\f") + 1 + (
        1 if fulltext.split("\n")[line - 1].startswith("\f") else 0)


def where(fulltext, file, line, paged=True):
    """Locator for a reader: file, page and line, e.g. `wachi2023.txt p.5 l.236`. No page if the PDF is not held."""
    if line is None:
        return f"`{file}` NOT FOUND"
    page = page_of(fulltext, line) if paged else None
    return f"`{file}` p.{page} l.{line}" if page else f"`{file}` l.{line}"


def find(fulltext, phrase):
    """Hit for `phrase` in a raw full text, or None."""
    line = locate(build_index(fulltext), phrase)
    return None if line is None else Hit(line, fulltext.split("\n")[line - 1].strip())


def missing_in_fulltext(uses, fulltexts):
    """[Use] -> problems for phrases that are not in the full text of their source. Sources without full text are skipped."""
    indexes = {k: build_index(t) for k, t in fulltexts.items()}
    return [f"{u.where}: quote not in 045_fulltext/{u.key}.txt: \"{u.phrase}\""
            for u in uses if u.key in indexes and locate(indexes[u.key], u.phrase) is None]


def not_covered_by_extracts(uses, extracts, cited):
    """[Use] -> problems for phrases that are not in the extracts that their row cites.

    extracts: {key: [row]}; cited: {use.where: [extract ids]} (the row's evidence column).
    """
    out = []
    for u in uses:
        ids = cited.get(u.where, [])
        known = {r["id"]: r for r in extracts.get(u.key, [])}
        out += [f"{u.where}: evidence {i} is not in 047_extracts/{u.key}/extracts.csv" for i in ids if i not in known]
        index = build_index("\n".join(known[i]["text"] for i in ids if i in known))
        if locate(index, u.phrase) is None:
            out.append(f"{u.where}: quote not in its cited extracts {ids or '(none)'}: \"{u.phrase}\"")
    return out


def report(extracts, uses, fulltexts, manifest):
    """Markdown report: for each source, its key extracts and every quote used, each with file:line and context."""
    by_key = {}
    for u in uses:
        by_key.setdefault(u.key, []).append(u)
    out = ["# Back-check report", "",
           "Generated by `300_render/build.py`. Each entry gives the file, the PDF page and the line of the stored full text.",
           "To check a quote, open the file at that line, or search the PDF for the phrase.", ""]
    for row in manifest:
        key, text = row["key"], fulltexts[row["key"]]
        index = build_index(text)
        raw = text.split("\n")
        out += [f"## {key}", "",
                f"Full text: `045_fulltext/{row['file']}` ({row['lines']} lines). Source: {row['source_url'] or 'n/a'}. "
                f"PDF: {'`045_fulltext/pdf/' + key + '.pdf`, ' + row['pages'] + ' pages' if row['pdf_sha256'] else 'not held'}.", ""]
        if extracts.get(key):
            out += ["### Key extracts", ""]
            for e in extracts[key]:
                line = locate(index, e["text"])
                clean = f" Authors' LaTeX: `{e['tex']}`" if e.get("tex", "").strip() else ""
                out.append(f"- **{e['id']}** ({e['kind']}, {e['locator'] or 'no locator'}) {where(text, row['file'], line, bool(row['pdf_sha256']))}: "
                           f"{e['text']}{clean}")
            out.append("")
        if by_key.get(key):
            out += ["### Quotes used", ""]
            for u in by_key[key]:
                line = locate(index, u.phrase)
                context = raw[line - 1].strip()[:300] if line else "NOT FOUND"
                out.append(f"- \"{u.phrase}\" — used in {u.where} — {where(text, row['file'], line, bool(row['pdf_sha256']))} — context: {context}")
            out.append("")
    stored = {row["key"] for row in manifest}
    rest = [u for u in uses if u.key not in stored]
    if rest:
        out += ["## Quotes from sources without stored full text", "",
                "The build cannot locate these. Each one is in a note, but the note is the only record.", ""]
        out += [f"- \"{u.phrase}\" — used in {u.where}" for u in rest] + [""]
    return "\n".join(out) + "\n"


def attribute(phrase, indexes):
    """Key of the first stored full text that contains the phrase, or "" if none does."""
    return next((k for k, index in indexes.items() if locate(index, phrase) is not None), "")


def stale_files(manifest, hashes):
    """Problems for stored files whose hash differs from the manifest. hashes: {(key, 'pdf'|'txt'): sha256 or None}."""
    out = []
    for row in manifest:
        for kind in ("pdf", "txt"):
            want, have = row[f"{kind}_sha256"], hashes.get((row["key"], kind))
            if want and have != want:
                out.append(f"045_fulltext: {row['key']} {kind} does not match the manifest; run 045_fulltext/extract.py")
    return out


def body_of(fulltext):
    """The text before its reference list (the last line that is just "References" or "Bibliography")."""
    lines = fulltext.split("\n")
    last = max((i for i, x in enumerate(lines) if x.strip().lstrip("\f").lower() in ("references", "bibliography")), default=len(lines))
    return "\n".join(lines[:last])


def term_hits(fulltext, terms):
    """[(term, line)] for each occurrence of a search term in the body. A term matches at a word start, any case."""
    hits = []
    for number, line in enumerate(body_of(fulltext).split("\n"), 1):
        low = line.lower()
        for term in terms:
            start = low.find(term.lower())
            while start >= 0:
                if start == 0 or not low[start - 1].isalnum():
                    hits.append((term, number))
                start = low.find(term.lower(), start + 1)
    return hits


def absence_problems(cells, terms_by_condition, fulltexts):
    """An absence cell records how many search hits were read; a different count today means new text to review."""
    out = []
    for c in cells:
        if c["evidence_type"] != "absence":
            continue
        hits = len(term_hits(fulltexts[c["tool"]], terms_by_condition[c["condition"]]))
        if str(hits) != c["hits_reviewed"].strip():
            out.append(f"cell {c['tool']} {c['condition']}: absence claim reviewed {c['hits_reviewed'] or 0} hits, "
                       f"but the search finds {hits}; read them (out/backcheck.md) and update hits_reviewed")
    return out


def absence_report(cells, terms_by_condition, fulltexts, manifest):
    """Markdown: for each absence cell, the terms searched and where each hit is."""
    rows = {m["key"]: m for m in manifest}
    out = ["## Absence claims", "", "A cell of this type says that the paper does not use a condition. "
           "The build searched the body of the paper for the condition's terms; every hit is listed and was read.", ""]
    for c in cells:
        if c["evidence_type"] != "absence":
            continue
        text, row = fulltexts[c["tool"]], rows[c["tool"]]
        hits = term_hits(text, terms_by_condition[c["condition"]])
        places = "; ".join(f"\"{t}\" {where(text, row['file'], n, bool(row['pdf_sha256']))}" for t, n in hits) or "no hits"
        out.append(f"- **{c['tool']} {c['condition']}** ({c['reason']}) Terms: {', '.join(terms_by_condition[c['condition']])}. Hits: {places}")
    return "\n".join(out) + "\n\n"


def formula_problems(extracts, tex_sources, images):
    """A formula given in LaTeX must be verbatim in the authors' source; without a source, a page image must exist.

    extracts: {key: [row]}; tex_sources: {key: all .tex text}; images: {(key, extract id)} that exist on disk.
    """
    out = []
    for key, rows in extracts.items():
        for e in rows:
            if not e.get("tex", "").strip():
                continue
            if key in tex_sources:
                if compact(e["tex"]) not in compact(tex_sources[key]):
                    out.append(f"extract {key} {e['id']}: LaTeX is not verbatim in 045_fulltext/tex/{key}/")
            elif (key, e["id"]) not in images:
                out.append(f"extract {key} {e['id']}: no LaTeX source for {key}; store a page image 047_extracts/{key}/{e['id']}.png")
    return out


def misattributed_quotes(texts, indexes, cite_pattern):
    """A quote of two or more words must be in a source cited next to it: the citation that follows it or precedes it.

    texts: {name: text}; indexes: {key: Index}; cite_pattern: compiled regex whose group 1 is a citation key.
    Quotes whose nearest cited sources are not stored cannot be tested here and are skipped.
    """
    out = []
    for name, text in texts.items():
        for m in QUOTED.finditer(text):
            phrase = m.group(1)
            if len(phrase.split()) < 2:
                continue
            after = [c.group(1) for c in cite_pattern.finditer(text[m.end():])][:2]
            before = [c.group(1) for c in cite_pattern.finditer(text[:m.start()])][-1:]
            near = [k for k in after + before if k in indexes]
            if near and not any(locate(indexes[k], phrase) is not None for k in near):
                out.append(f"{name}: quote \"{phrase}\" is not in the sources cited next to it ({', '.join(near)})")
    return out
